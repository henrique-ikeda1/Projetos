# Entrada de dados
'''
Solicite ao usuário que informe um número inteiro e verifique se ele é maior ou igual a 18. Se for maior ou igual a 18, exiba a mensagem "Você é maior de idade." Caso contrário, exiba a mensagem "Você é menor de idade."
'''
idade = int(input("Informe sua idade: "))
if idade >= 18:
    print("Você é maior de idade.")
else:
    print("Você é menor de idade.")