# Listas são coleções ordenadas e mutáveis de elementos.
# Elas podem conter elementos de diferentes tipos, incluindo outras listas.
# Exemplos de listas:
nomes = ["Ana", "Bruno", "Carlos"]

nomes [1] = "Beatriz"  # Alterando o segundo elemento da lista
print(nomes)  # Saída: ['Ana', 'Beatriz', 'Carlos']